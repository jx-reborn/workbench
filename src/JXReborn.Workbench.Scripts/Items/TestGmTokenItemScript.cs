                });
                return ValueTask.CompletedTask;
            }),
            new DialogOption("Đặt Task(ID) = 1", static c =>
            {
                c.AskClientForNumber("Nhập Task ID cần đặt = 1 (0..65535):", 0, 65535, static (nc, taskId) =>
                {
                    ushort id = (ushort)Math.Clamp(taskId, 0, 65535);
                    nc.SetTask(id, 1);
                    nc.SendSystemMessage($"[GM] Đã đặt Task({id}) = 1.");
                    return ValueTask.CompletedTask;
                });
                return ValueTask.CompletedTask;
            }),
            new DialogOption("Đặt Task(ID) = 0", static c =>
            {
                c.AskClientForNumber("Nhập Task ID cần đặt = 0 (0..65535):", 0, 65535, static (nc, taskId) =>
                {
                    ushort id = (ushort)Math.Clamp(taskId, 0, 65535);
                    nc.SetTask(id, 0);
                    nc.SendSystemMessage($"[GM] Đã đặt Task({id}) = 0.");
                    return ValueTask.CompletedTask;
                });
                return ValueTask.CompletedTask;
            }),
            new DialogOption("Quay lại", static c =>
            {
                OpenRootMenu((ZoneScriptDialogContextBase)c);
                return ValueTask.CompletedTask;
            }));
    }

    // ==================== SHARED TEMPLATE / BAG HELPERS ====================
    private static ItemTemplate ResolveOrCreateTemplate(
        ZoneScriptDialogContextBase ctx,
        string preferredCode,
        string fallbackName,
        ItemGenreKind genre,
        ItemQualityKind quality,
        short detailType,
        short particularType,
        byte level,
        byte width,
        byte height)
    {
        IItemTemplateCatalog? catalog = ctx.ExecutionContext.Assets.ItemTemplateCatalog;
        if (catalog is not null)
        {
            if (catalog.TryGetItem(genre, detailType, particularType, level, out ItemTemplate? exactTpl, quality) && exactTpl is not null)
            {
                return exactTpl;
            }

            if (catalog.TryGetItemByCode(preferredCode, out ItemTemplate? byCodeTpl) && byCodeTpl is not null)
            {
                return byCodeTpl;
            }

            ItemTemplate? match = catalog.AllItems.FirstOrDefault(
                t => t.Genre == genre && t.DetailType == detailType && t.ParticularType == particularType);
            if (match is not null)
            {
                return match;
            }
        }

        return new ItemTemplate(
            Id: (detailType * 1000) + particularType + level,
            Code: preferredCode,
            Name: fallbackName,
            Genre: genre,
            Quality: quality,
            DetailType: detailType,
            ParticularType: particularType,
            Level: level,
            ElementSeries: ElementSeries.Metal,
            GridWidthCells: width,
            GridHeightCells: height,
            ObjDataId: 1,
            AppearanceResId: 0,
            PriceGold: 100,
            MaxStackCount: 1,
            BaseAttributes: [],
            Requirements: []);
    }

    private static bool TryPlaceAndSyncBagSlot(PlayerZoneState player, PlayerItemSlot slot)
    {
        if (player.Inventory.TryAddOrAutoPlaceItem(slot, ItemContainerPlace.EquipRoom, 0, 0, player))
        {
            PlayerItemSyncSnapshot snap = PlayerItemSyncSnapshot.CreateFromSlot(slot);
            player.InventorySink.SendItemSync(in snap);
            return true;
        }

        return false;
    }
