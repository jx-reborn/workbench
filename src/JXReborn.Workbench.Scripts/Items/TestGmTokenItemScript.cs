    private static void DegradeFirstEquipmentDurability(PlayerZoneState player, bool setToOne)
    {
        PlayerItemSlot? equip = player.Inventory.AllItems
            .Where(static s => s.ContainerPlace == ItemContainerPlace.EquipRoom && s.Genre == ItemGenreKind.Equipment && s.MaxDurability > 1)
            .OrderBy(static s => s.GridY)
            .ThenBy(static s => s.GridX)
            .FirstOrDefault();

        if (equip is null)
        {
            return;
        }

        equip.CurrentDurability = setToOne ? (ushort)1 : (ushort)Math.Max(1, equip.MaxDurability - 5);
        player.InventorySink.SendItemDurabilitySync(equip.RuntimeItemId, equip.MaxDurability, equip.CurrentDurability);
    }

    private static int ClearBagKeepingGmToken(PlayerZoneState player)
    {
        List<PlayerItemSlot> toRemove = player.Inventory.AllItems
            .Where(static s =>
                s.ContainerPlace == ItemContainerPlace.EquipRoom &&
                !(s.Genre == ItemGenreKind.MagicScript && s.DetailType == 1 && s.ParticularType == GmTokenParticularType))
            .ToList();

        int removedCount = 0;
        foreach (PlayerItemSlot slot in toRemove)
        {
            if (player.Inventory.TryRemoveItem(slot.RuntimeItemId, out _, player))
            {
                player.InventorySink.SendItemRemove(slot.RuntimeItemId);
                removedCount++;
            }
        }

        return removedCount;
    }

    private static int FillBagToCapacity(ZoneScriptDialogContextBase ctx)
    {
        int added = 0;
        while (ctx.FreeBagCellCount > 0 && added < 60)
        {
            if (!TryGrantMedicine(ctx, detailType: 0, particularType: 0, level: 1, "kim-sang-duoc-tieu", "Kim Sáng Dược (tiểu)"))
            {
                break;
            }

            added++;
        }

        return added;
    }

