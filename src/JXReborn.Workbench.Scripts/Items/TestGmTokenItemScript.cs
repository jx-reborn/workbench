    private static void EnsureLevel(ZoneScriptDialogContextBase ctx, byte targetLevel)
    {
        PlayerZoneState player = ctx.Player;
        if (player.Level < targetLevel)
        {
            PlayerSeriesGrowthRuleTemplate growth =
                ctx.ExecutionContext.Assets.PlayerTemplateCatalog?.GetSeriesGrowthRule(player.Series)
                ?? PlayerTemplateCatalog.GetDefaultSeriesGrowthRule(player.Series);

            int levelsToGain = targetLevel - player.Level;
            for (int lv = 0; lv < levelsToGain && player.Level < 200; lv++)
            {
                player.Level++;
                player.UnallocatedAttributePoints = (ushort)Math.Min(
                    ushort.MaxValue,
                    player.UnallocatedAttributePoints + Math.Max(1, growth.AttributePointsPerLevel));
                player.UnallocatedSkillPoints = (ushort)Math.Min(
                    ushort.MaxValue,
                    player.UnallocatedSkillPoints + Math.Max(1, growth.SkillPointsPerLevel));
                player.MaxLife = (ushort)Math.Clamp(player.MaxLife + Math.Max(1, growth.LifePerLevel), 1, ushort.MaxValue);
                player.MaxMana = (ushort)Math.Clamp(player.MaxMana + Math.Max(1, growth.ManaPerLevel), 1, ushort.MaxValue);
                player.MaxStamina = (ushort)Math.Clamp(player.MaxStamina + Math.Max(1, growth.StaminaPerLevel), 1, ushort.MaxValue);
                player.OutboundSink.SendPlayerLevelUpSync(player);
            }
        }

        RestoreVitals(player);
    }

    private static void AddAttributePoints(ZoneScriptDialogContextBase ctx, int attrPoints)
    {
        PlayerZoneState player = ctx.Player;
        ctx.ExecutionContext.Assets.FactionProgressionManager.AddBonusAttributePoints(player, attrPoints);
        player.CombatSink.SendPlayerAttributeSync(0, player.Strength, player.EffectiveStrength, player.UnallocatedAttributePoints);
        player.CombatSink.SendPlayerAttributeSync(1, player.Dexterity, player.EffectiveDexterity, player.UnallocatedAttributePoints);
        player.CombatSink.SendPlayerAttributeSync(2, player.Vitality, player.EffectiveVitality, player.UnallocatedAttributePoints);
        player.CombatSink.SendPlayerAttributeSync(3, player.Energy, player.EffectiveEnergy, player.UnallocatedAttributePoints);
    }

    private static void RestoreVitals(PlayerZoneState player)
    {
        player.RestoreFullVitals();
        player.OutboundSink.SendNormalVitalSync(player);
    }

